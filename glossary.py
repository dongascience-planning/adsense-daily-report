def tips_for(text, limit=4):
    """인사이트 텍스트에 등장한 용어를 우선순위 순으로 최대 limit개 반환. [(표시명, 설명), ...]"""
    if not text:
        return []
    found = []
    for term, aliases, desc in GLOSSARY:
        if any(alias in text for alias in aliases):
            found.append((term, desc))
        if len(found) >= limit:
            break
    return found
